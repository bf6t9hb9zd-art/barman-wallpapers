// ── i18n ENGINE ─────────────────────────────────
let currentLanguage = localStorage.getItem("language") || "en";

function t(key, vars = {}) {
    const dict = i18n[currentLanguage] || i18n.en;
    let str = dict[key];
    if (str === undefined) str = i18n.en[key] || key;
    return str.replace(/\{(\w+)\}/g, (_, k) => vars[k] !== undefined ? vars[k] : `{${k}}`);
}

function applyTranslations(root = document) {
    // text content: <tag data-i18n="key">
    root.querySelectorAll("[data-i18n]").forEach(el => {
        el.textContent = t(el.getAttribute("data-i18n"));
    });

    // placeholders: <input data-i18n-placeholder="key">
    root.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
        el.placeholder = t(el.getAttribute("data-i18n-placeholder"));
    });

    // title attributes: <tag data-i18n-title="key">
    root.querySelectorAll("[data-i18n-title]").forEach(el => {
        el.title = t(el.getAttribute("data-i18n-title"));
    });
}

function changeLanguage(lang) {
    if (!i18n[lang]) lang = "en";
    currentLanguage = lang;
    localStorage.setItem("language", lang);
    applyTranslations();
    const ls = document.getElementById("languageSelect");
    if (ls) ls.value = lang;

    // notify other code (e.g. gallery reload, dashboard labels)
    window.dispatchEvent(new CustomEvent("languageChanged", { detail: { lang } }));
}

window.t = t;
window.changeLanguage = changeLanguage;
window.applyTranslations = applyTranslations;
window.i18n = i18n;
